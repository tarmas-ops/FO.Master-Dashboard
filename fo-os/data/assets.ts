const USD = 940;

function security(
  id: string,
  ticker: string,
  issuer: string,
  opts: {
    assetClass: "MERCADOS_PUBLICOS" | "RENTA_FIJA";
    subAssetClass: string;
    sector: PublicSecurity["sector"];
    country: PublicSecurity["country"];
    currency: PublicSecurity["currency"];
    shares: number;
    price: number;
    costTotal: number;
    dividendYield: number;
    acquisitionDate: string;
  },
): PublicSecurity {
  const fx = opts.currency === "USD" ? USD : 1;
  const value = Math.round(opts.shares * opts.price * fx);
  return {
    id,
    name: issuer,
    ticker,
    issuer,
    assetClass: opts.assetClass,
    subAssetClass: opts.subAssetClass,
    sector: opts.sector,
    country: opts.country,
    currency: opts.currency,
    shares: opts.shares,
    price: opts.price,
    currentValue: value,
    acquisitionCost: opts.costTotal,
    acquisitionDate: opts.acquisitionDate,
    ownerEntityId: "andes",
    ownershipPercentage: 1,
    valuationMethod: "Precio de mercado",
    lastValuationDate: "2026-09-02",
    liquid: true,
    dividendYield: opts.dividendYield,
    dividendsLTM: Math.round(value * opts.dividendYield),
  };
}

